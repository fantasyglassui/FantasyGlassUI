local function EachFeature(fn)
    for _, group in ipairs(groups) do
        for _, opt in ipairs(group[2]) do
            if not ns:FeatureHidden(opt[1]) then fn(opt[1], opt[2]) end
        end
    end
end
-- Set every switch a preset has an opinion on. Returns how many changed.
function ns:ApplyPreset(preset)
    local changed = 0
    EachFeature(function(key)
        local v = ns:PresetValue(preset, key)
        if v ~= nil and (ns.db[key] and true or false) ~= v then
            ns.db[key] = v
            changed = changed + 1
        end
    end)
    return changed
end
-- Which preset the switches match right now, or nil when they have been set by hand.
function ns:CurrentPreset()
    for _, preset in ipairs({ "STANDARD", "EVERYTHING", "MINIMAL", "RESTYLE" }) do
        local same = true
        EachFeature(function(key)
            local v = ns:PresetValue(preset, key)
            if v ~= nil and (ns.db[key] and true or false) ~= v then same = false end
        end)
        if same then return preset end
    end
end
function ns:CountFeatures()
    local on, total = 0, 0
    EachFeature(function(key)
        total = total + 1
        if ns.db[key] then on = on + 1 end
    end)
    return on, total
end

